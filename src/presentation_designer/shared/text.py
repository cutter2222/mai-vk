"""Мелкие текстовые утилиты для сообщений пользователю."""

from __future__ import annotations


def plural(n: int, one: str, few: str, many: str) -> str:
    """Русская форма слова при числе: 1 вариант, 2 варианта, 5 вариантов.

    Сообщения о ходе задания видит пользователь в карточке генерации, и «1 вариантов»
    там читается как сбой, а не как оборот речи.
    """
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many
