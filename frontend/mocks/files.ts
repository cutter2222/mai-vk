/**
 * Генерация файлов-заглушек прямо в браузере: миниатюры слайдов как PNG через canvas,
 * PPTX как настоящий минимальный OOXML-пакет, PDF как валидный однострочный документ.
 * Скачанные файлы открываются, а не оказываются JSON под чужим расширением.
 */

const cache = new Map<string, Blob>();

export function slidePng(key: string, title: string, subtitle: string, accent = "#0077FF", width = 1280): Promise<Blob> {
  const cached = cache.get(key);
  if (cached) return Promise.resolve(cached);
  const height = Math.round((width * 9) / 16);
  const canvas = document.createElement("canvas");
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext("2d");
  if (!ctx) return Promise.resolve(new Blob());
  ctx.fillStyle = "#ffffff";
  ctx.fillRect(0, 0, width, height);
  ctx.fillStyle = accent;
  ctx.fillRect(0, 0, width, 10);
  ctx.fillRect(width * 0.05, height * 0.92, width * 0.08, height * 0.04);
  ctx.fillStyle = "#111111";
  ctx.font = `600 ${Math.round(width * 0.036)}px Arial`;
  wrap(ctx, title, width * 0.05, height * 0.16, width * 0.9, width * 0.045);
  ctx.fillStyle = "#333333";
  ctx.font = `${Math.round(width * 0.022)}px Arial`;
  wrap(ctx, subtitle, width * 0.05, height * 0.38, width * 0.55, width * 0.03);
  ctx.strokeStyle = "#d0d7de";
  ctx.strokeRect(width * 0.65, height * 0.32, width * 0.3, height * 0.45);
  ctx.fillStyle = accent;
  [0.45, 0.7, 0.55, 0.85].forEach((h, i) => {
    const barW = width * 0.05;
    const x = width * 0.68 + i * barW * 1.35;
    const barH = height * 0.4 * h;
    ctx.fillRect(x, height * 0.75 - barH, barW, barH);
  });
  return new Promise((resolve) => {
    canvas.toBlob((blob) => {
      const b = blob ?? new Blob();
      cache.set(key, b);
      resolve(b);
    }, "image/png");
  });
}

function wrap(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, maxW: number, lineH: number) {
  const words = text.split(" ");
  let line = "";
  let yy = y;
  for (const w of words) {
    const test = line ? `${line} ${w}` : w;
    if (ctx.measureText(test).width > maxW && line) {
      ctx.fillText(line, x, yy);
      line = w;
      yy += lineH;
    } else {
      line = test;
    }
  }
  if (line) ctx.fillText(line, x, yy);
}

/** Минимальный валидный PDF с одной страницей и текстом. */
export function pdfBlob(text: string): Blob {
  const content = `BT /F1 24 Tf 72 700 Td (${text.replace(/[()\\]/g, "")}) Tj ET`;
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 960 540] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ];
  let body = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((obj, i) => {
    offsets.push(body.length);
    body += `${i + 1} 0 obj\n${obj}\nendobj\n`;
  });
  const xref = body.length;
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.forEach((o) => {
    body += `${String(o).padStart(10, "0")} 00000 n \n`;
  });
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return new Blob([body], { type: "application/pdf" });
}

/** Автономный HTML-просмотр колоды. */
export function htmlBlob(title: string, slides: string[]): Blob {
  const body = slides
    .map(
      (s, i) =>
        `<section style="width:960px;height:540px;margin:24px auto;border:1px solid #ddd;padding:40px;box-sizing:border-box;font-family:Arial"><h2 style="margin:0 0 16px">${i + 1}. ${s}</h2><p>Текст слайда выделяется и копируется.</p></section>`,
    )
    .join("");
  return new Blob([`<!doctype html><html lang="ru"><head><meta charset="utf-8"><title>${title}</title></head><body style="background:#f4f4f4">${body}</body></html>`], {
    type: "text/html",
  });
}

